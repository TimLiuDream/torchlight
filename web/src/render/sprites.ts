const hero24Cache = new Map<string, HTMLCanvasElement>();

/** 取主角 24x24 帧: phase 0/1 两帧交替 */
export function hero24Frame(key: string, phase: number): HTMLCanvasElement {
  const k = `${key}:${phase & 1}`;
  let cv = hero24Cache.get(k);
  if (!cv) {
    const def = HERO24[key];
    if (!def) throw new Error(`unknown hero24: ${key}`);
    const rows = def.frames[phase & 1];
    cv = document.createElement("canvas");
    cv.width = 24;
    cv.height = 24;
    const ctx = cv.getContext("2d")!;
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      for (let x = 0; x < row.length; x++) {
        const color = def.palette[row[x]];
        if (color) {
          ctx.fillStyle = color;
          ctx.fillRect(x, y, 1, 1);
        }
      }
    }
    hero24Cache.set(k, cv);
  }
  return cv;
}

let cache = new Map<string, HTMLCanvasElement>();
// 每个精灵 "1"(眼色)像素坐标 -> 发光眼叠层用
const eyeMap = new Map<string, Array<[number, number]>>();

function bake(key: string, def: SpriteDef): HTMLCanvasElement {
  const h = def.rows.length;
  const w = def.rows[0].length;
  const cv = document.createElement("canvas");
  cv.width = w;
  cv.height = h;
  const ctx = cv.getContext("2d")!;
  const eyes: Array<[number, number]> = [];
  for (let y = 0; y < h; y++) {
    const row = def.rows[y];
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === "." || ch === " ") continue;
      if (ch === "1") eyes.push([x, y]);
      const color = def.palette[ch];
      if (!color) continue;
      ctx.fillStyle = color;
      ctx.fillRect(x, y, 1, 1);
    }
  }
  eyeMap.set(key, eyes);
  return cv;
}

export function sprite(key: string): HTMLCanvasElement {
  let cv = cache.get(key);
  if (!cv) {
    const def = DEFS[key];
    if (!def) throw new Error(`unknown sprite: ${key}`);
    cv = bake(key, def);
    cache.set(key, cv);
  }
  return cv;
}

/** 精灵中 "1"(眼色)像素的坐标列表 —— 发光眼叠层用 */
export function spriteEyes(key: string): Array<[number, number]> {
  return eyeMap.get(key) ?? [];
}

/** 画一个角色精灵, 以 tile 中心对齐。 */
export function drawSprite(
  ctx: CanvasRenderingContext2D, key: string, tileX: number, tileY: number, tile = 16, scale = 1,
): void {
  const cv = sprite(key);
  const w = cv.width * scale;
  const h = cv.height * scale;
  const off = (tile - 12 * scale) / 2;
  ctx.drawImage(cv, Math.round(tileX * tile + off), Math.round(tileY * tile + off), w, h);
}

